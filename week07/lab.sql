BEGIN;
CREATE SCHEMA week07;
CREATE TABLE week07.column_key (id INTEGER PRIMARY KEY);
CREATE TABLE week07.table_key (id INTEGER, PRIMARY KEY (id));
CREATE TABLE week07.named_key (id INTEGER, CONSTRAINT pk_named_key PRIMARY KEY(id));
CREATE TABLE week07.existing_table (id INTEGER);
ALTER TABLE week07.existing_table ADD CONSTRAINT pk_existing_table PRIMARY KEY(id);
CREATE TABLE week07.students (
    student_id SERIAL PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(150) UNIQUE,
    faculty VARCHAR(50)
);
